/**
 * Generates supabase/seed.sql from the same DEMO DATA used by the in-memory
 * store, so both storage modes show identical, clearly-labeled sample data.
 *
 *   npm run db:seed:generate
 *
 * Every row is inserted with is_demo = true. No transaction signatures are
 * generated.
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { createDemoSeed } from "../src/lib/data/demo-seed";

const q = (v: unknown): string => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number" || typeof v === "bigint") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  if (Array.isArray(v)) return v.length ? `array[${v.map(q).join(", ")}]::text[]` : "'{}'::text[]";
  return `'${String(v).replace(/'/g, "''")}'`;
};

// Stable UUIDs derived from demo ids so foreign keys line up.
const ids = new Map<string, string>();
const uuid = (key: string) => {
  if (!ids.has(key)) {
    const n = (ids.size + 1).toString(16).padStart(12, "0");
    ids.set(key, `00000000-0000-4000-8000-${n}`);
  }
  return ids.get(key)!;
};

const seed = createDemoSeed();
const out: string[] = [
  "-- AUTO-GENERATED by scripts/generate-seed-sql.ts — DEMO DATA ONLY (fictional projects).",
  "-- Do not edit by hand. Regenerate with: npm run db:seed:generate",
  "begin;",
  "",
];

for (const a of seed.applications) {
  out.push(
    `insert into public.applications (id, reference, project_name, ticker, contract_address, website, twitter, telegram, discord, description, applicant_wallet, campaign_package, application_status, payment_status, is_demo, created_at, updated_at) values (${[
      uuid(a.id), a.reference, a.projectName, a.ticker, a.contractAddress, a.website, a.twitter, a.telegram, a.discord, a.description,
      a.applicantWallet, a.campaignPackage, a.status, a.paymentStatus, true, a.createdAt, a.updatedAt,
    ].map(q).join(", ")});`,
  );
}
out.push("");
for (const s of seed.screenings) {
  out.push(
    `insert into public.screening (id, application_id, liquidity_score, holder_distribution_score, developer_activity_score, community_score, trading_activity_score, token_authorities_score, tokenomics_score, manipulation_score, market_cap_usd, liquidity_usd, holder_count, top10_holder_pct, mint_authority_revoked, freeze_authority_revoked, risk_flags, screening_notes, recommendation, risk_level, reviewer_label, created_at) values (${[
      uuid(s.id), uuid(s.applicationId), s.liquidityScore, s.holderDistributionScore, s.developerActivityScore, s.communityScore,
      s.tradingActivityScore, s.tokenAuthoritiesScore, s.tokenomicsScore, s.manipulationScore, s.marketCapUsd, s.liquidityUsd,
      s.holderCount, s.top10HolderPct, s.mintAuthorityRevoked, s.freezeAuthorityRevoked, s.riskFlags, s.screeningNotes,
      s.recommendation, s.riskLevel, s.reviewedBy, s.createdAt,
    ].map(q).join(", ")});`,
  );
}
out.push("");
for (const c of seed.campaigns) {
  out.push(
    `insert into public.campaigns (id, slug, application_id, project_name, ticker, token_address, description, website, twitter, telegram, discord, campaign_package, total_campaign_fee, campaign_status, featured, risk_level, screening_date, market_cap_at_screening_usd, liquidity_at_screening_usd, holder_count_at_screening, snapshot_at, eligible_supply, is_demo, created_at) values (${[
      uuid(c.id), c.slug, c.applicationId ? uuid(c.applicationId) : null, c.projectName, c.ticker, c.tokenAddress, c.description,
      c.website, c.twitter, c.telegram, c.discord, c.campaignPackage, c.totalCampaignFeeCents, c.status, c.featured, c.riskLevel,
      c.screeningDate, c.marketCapAtScreeningUsd, c.liquidityAtScreeningUsd, c.holderCountAtScreening, c.snapshotAt,
      c.eligibleSupply, true, c.createdAt,
    ].map(q).join(", ")});`,
  );
}
out.push("");
for (const p of seed.purchases) {
  out.push(
    `insert into public.treasury_purchases (id, campaign_id, usdc_spent_cents, token_amount, purchase_status, transaction_signature, notes, is_demo, executed_at) values (${[
      uuid(p.id), uuid(p.campaignId), p.usdcSpentCents, p.tokenAmount, p.status, null, p.notes, true, p.executedAt,
    ].map(q).join(", ")});`,
  );
}
out.push("");
for (const d of seed.distributions) {
  out.push(
    `insert into public.distributions (id, campaign_id, wallet_address, runner_balance, eligible_supply, reward_percentage, reward_amount, distribution_status, transaction_signature, is_demo, created_at) values (${[
      uuid(d.id), uuid(d.campaignId), d.walletAddress, d.runnerBalance, d.eligibleSupply, d.rewardPercentage, d.rewardAmount,
      d.distributionStatus, null, true, d.createdAt,
    ].map(q).join(", ")});`,
  );
}
out.push("", "commit;", "");

const target = join(process.cwd(), "supabase", "seed.sql");
writeFileSync(target, out.join("\n"));
console.log(`Wrote ${target}`);
